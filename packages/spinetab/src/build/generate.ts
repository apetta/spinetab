// Generated content depends only on the adapter set and credential origins; it must contain no paths or environment values.

import { createHash } from "node:crypto";
import { normaliseCredentialOrigins } from "../core/origins.ts";
import {
	compareText,
	isAdapterName,
	rowOfKind,
	type SpinetabAdapterName,
} from "./adapters.ts";
import { SpinetabBuildError } from "./messages.ts";

export const GENERATED_HEADER = "// Generated by spinetab. Do not edit.";

/** Grammar version for loader cache keys; never part of the output. */
export const GENERATOR_VERSION = "spinetab-worker-1";

export function generateWorker(
	adapters: readonly string[],
	credentialOrigins: readonly string[] = [],
): string {
	if (!adapters.every(isAdapterName)) {
		throw new SpinetabBuildError({ code: "unknown-adapter" });
	}
	const kinds = [...new Set<SpinetabAdapterName>(adapters)].sort(compareText);
	const byRuntime = new Map<string, string[]>();
	for (const kind of kinds) {
		const row = rowOfKind(kind);
		const factory = row.factories[kind];
		if (factory === undefined) {
			throw new SpinetabBuildError({ code: "unknown-adapter" });
		}
		byRuntime.set(row.runtime, [
			...(byRuntime.get(row.runtime) ?? []),
			factory,
		]);
	}
	const lines = [GENERATED_HEADER];
	for (const runtime of [...byRuntime.keys()].sort(compareText)) {
		const factories = (byRuntime.get(runtime) ?? []).sort(compareText);
		lines.push(
			`import { ${factories.join(", ")} } from ${JSON.stringify(runtime)};`,
		);
	}
	lines.push('import { defineWorker } from "spinetab/worker";');
	const calls = kinds
		.map((kind) => `${rowOfKind(kind).factories[kind]}()`)
		.join(", ");
	const origins = normaliseCredentialOrigins(credentialOrigins);
	const options =
		origins.length === 0
			? ""
			: `, { credentialOrigins: ${JSON.stringify(origins)} }`;
	lines.push(`export default defineWorker(() => [${calls}]${options});`);
	return `${lines.join("\n")}\n`;
}

/** Runtime entries a generated worker imports (Vite `optimizeDeps.include`). */
export function runtimeSpecifiers(adapters: readonly string[]): string[] {
	const specifiers = new Set<string>();
	for (const kind of adapters) {
		if (isAdapterName(kind)) specifiers.add(rowOfKind(kind).runtime);
	}
	return [...specifiers].sort(compareText);
}

function hash12(text: string): string {
	return createHash("sha256").update(text).digest("hex").slice(0, 12);
}

export function devNameForGenerated(workerText: string): string {
	return `spinetab-${hash12(workerText)}`;
}

export function devNameForWorkerFile(
	relativePosixPath: string,
	content: string,
): string {
	return `spinetab-${hash12(`${relativePosixPath}\n${content}`)}`;
}

const MODULE_OPTIONS = /\{\s*type:\s*"module"\s*\}/;

/**
 * The development transform of the shipped `auto/wiring.js`: the one
 * `{ type: "module" }` literal gains the name. Production never calls this.
 */
export function applyDevName(wiringText: string, name: string): string {
	if (!/^spinetab-[0-9a-f]{12}$/.test(name)) {
		throw new Error("spinetab: invalid development worker name.");
	}
	return wiringText.replace(
		MODULE_OPTIONS,
		`{ type: "module", name: ${JSON.stringify(name)} }`,
	);
}
