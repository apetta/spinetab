// expected records the imported adapter set before peer availability checks. RESIDUAL_CASES also records current scanner output so known limitations remain explicit.

export interface Case {
	id: string;
	group:
		| "negative"
		| "positive"
		| "edge"
		| "extra"
		| "root"
		| "r21"
		| "fix"
		| "residual";
	file: string;
	code: string;
	expected: string[];
	note?: string;
	/** The file cannot be closed and is read by fallback. */
	fallback?: true;
	/**
	 * A known limitation. `kinds` and `fallback` are what the scanner
	 * reports today (never `expected`); `why` names the trigger and `remedy`
	 * the fix available to an application.
	 */
	residual?: {
		kinds: string[];
		fallback: boolean;
		why: string;
		remedy: string;
	};
}

