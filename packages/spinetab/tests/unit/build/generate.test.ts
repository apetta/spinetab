import { describe, expect, it } from "vitest";
import { ADAPTER_NAMES, ADAPTER_TABLE } from "../../../src/build/adapters.ts";
import {
	applyDevName,
	devNameForGenerated,
	devNameForWorkerFile,
	GENERATED_HEADER,
	generateWorker,
	runtimeSpecifiers,
} from "../../../src/build/generate.ts";

// The nine hostile strings from the security PoC (`security/escape`).
const HOSTILE = [
	"C:\\Users\\dev\\app\\live.worker.ts",
	'a"; globalThis.pwned = 1; //',
	"a'; globalThis.pwned = 1; //",
	// biome-ignore lint/suspicious/noTemplateCurlyInString: a deliberately hostile input.
	"a`${globalThis.pwned = 1}`",
	"line\nbreak",
	"sep\u2028and\u2029para",
	"*/ globalThis.pwned = 1; /*",
	"</script><script>alert(1)</script>",
	"\u0000nul",
];

interface Lexer {
	init: Promise<void>;
	parse(code: string): [{ n: string | undefined }[], unknown];
}

/** Import specifiers by es-module-lexer when installed, else a strict regex. */
async function specifiersOf(code: string): Promise<string[]> {
	const name = "es-module-lexer";
	try {
		const lexer = (await import(/* @vite-ignore */ name)) as Lexer;
		await lexer.init;
		const [imports] = lexer.parse(code);
		return imports.map((entry) => entry.n ?? "");
	} catch {
		return [...code.matchAll(/^import [^\n]* from ("[^"]+");$/gm)].map(
			(match) => JSON.parse(match[1] ?? '""') as string,
		);
	}
}

describe("generateWorker", () => {
	it("emits the exact grammar", () => {
		expect(
			generateWorker(["sse", "polling"], ["https://api.example.com"]),
		).toBe(
			[
				"// Generated by spinetab. Do not edit.",
				'import { pollingAdapter } from "spinetab/polling/runtime";',
				'import { sseAdapter } from "spinetab/sse/runtime";',
				'import { defineWorker } from "spinetab/worker";',
				'export default defineWorker(() => [pollingAdapter(), sseAdapter()], { credentialOrigins: ["https://api.example.com"] });',
				"",
			].join("\n"),
		);
	});

	it("emits the empty set without options", () => {
		expect(generateWorker([])).toBe(
			`${GENERATED_HEADER}\nimport { defineWorker } from "spinetab/worker";\nexport default defineWorker(() => []);\n`,
		);
	});

	it("groups both tRPC factories in one sorted import", () => {
		const text = generateWorker(["trpc-ws", "trpc-sse", "ai-sdk"]);
		expect(text).toContain(
			'import { trpcSseAdapter, trpcWsAdapter } from "spinetab/trpc/runtime";',
		);
		expect(text).toContain(
			"defineWorker(() => [aiSdkAdapter(), trpcSseAdapter(), trpcWsAdapter()])",
		);
	});

	it("is deterministic regardless of input order and duplicates", () => {
		const a = generateWorker([...ADAPTER_NAMES], ["https://b.example"]);
		const b = generateWorker([...ADAPTER_NAMES].reverse().concat(["polling"]), [
			"https://b.example",
			"https://b.example/",
		]);
		expect(a).toBe(b);
		const lines = a.split("\n");
		expect(lines[0]).toBe(GENERATED_HEADER);
		const imports = lines.filter((line) => line.startsWith("import "));
		expect(imports.at(-1)).toBe(
			'import { defineWorker } from "spinetab/worker";',
		);
		const runtimes = imports.slice(0, -1);
		expect(runtimes).toEqual([...runtimes].sort());
	});

	it("normalises, de-duplicates and sorts credential origins", () => {
		const text = generateWorker(
			["polling"],
			["https://B.example:443", "https://a.example/", "http://localhost:8080"],
		);
		const list = /credentialOrigins: (\[[^\]]*\])/.exec(text)?.[1] ?? "";
		expect(JSON.parse(list)).toEqual([
			"http://localhost:8080",
			"https://a.example",
			"https://b.example",
		]);
	});

	it("never embeds hostile strings", async () => {
		const text = generateWorker(["polling"], HOSTILE);
		for (const value of HOSTILE) expect(text).not.toContain(value);
		expect(text).not.toContain("credentialOrigins");
		for (const specifier of await specifiersOf(text)) {
			expect(
				specifier === "spinetab/worker" ||
					ADAPTER_TABLE.some((row) => row.runtime === specifier),
			).toBe(true);
		}
	});

	it("names only table specifiers for every adapter", async () => {
		const text = generateWorker([...ADAPTER_NAMES], ["https://a.example"]);
		const specifiers = await specifiersOf(text);
		expect(specifiers).toEqual([
			...ADAPTER_TABLE.map((row) => row.runtime).sort(),
			"spinetab/worker",
		]);
	});

	it("holds no path, environment, timestamp or version (–)", () => {
		const text = generateWorker([...ADAPTER_NAMES], ["https://a.example"]);
		expect(text).not.toMatch(/process\.env|import\.meta|\/Users\/|[A-Z]:\\/);
		expect(text).not.toMatch(/\d{4}-\d{2}-\d{2}|\b\d{10,}\b/);
		expect(text.split("\n").filter((line) => line.startsWith("//"))).toEqual([
			GENERATED_HEADER,
		]);
	});

	it("refuses names outside the table", () => {
		expect(() => generateWorker(["polling", "evil"])).toThrow(
			/^\[spinetab\] unknown-adapter: /,
		);
	});
});

describe("development name", () => {
	it("hashes the generated text to twelve lowercase hex", () => {
		const text = generateWorker(["polling"]);
		const name = devNameForGenerated(text);
		expect(name).toMatch(/^spinetab-[0-9a-f]{12}$/);
		expect(devNameForGenerated(text)).toBe(name);
		expect(devNameForGenerated(generateWorker(["polling", "sse"]))).not.toBe(
			name,
		);
		// SHA-256 of the text, first twelve characters.
		expect(devNameForGenerated("")).toBe("spinetab-e3b0c44298fc");
	});

	it("hashes the worker file's relative path and content at L2", () => {
		const a = devNameForWorkerFile("src/spinetab.worker.ts", "x");
		expect(a).toMatch(/^spinetab-[0-9a-f]{12}$/);
		expect(devNameForWorkerFile("app/spinetab.worker.ts", "x")).not.toBe(a);
		expect(devNameForWorkerFile("src/spinetab.worker.ts", "y")).not.toBe(a);
	});

	it("rewrites the shipped wiring literal and nothing else", () => {
		const shipped = [
			"const wiring = {",
			'\tworker: () => new SharedWorker(new URL("./worker.js", import.meta.url), { type: "module" }),',
			'\tlocal: () => import("./worker.js")',
			"};",
		].join("\n");
		const out = applyDevName(shipped, "spinetab-0123456789ab");
		expect(out).toBe(
			shipped.replace(
				'{ type: "module" }',
				'{ type: "module", name: "spinetab-0123456789ab" }',
			),
		);
		expect(() => applyDevName(shipped, 'x", evil: "')).toThrow();
	});
});

describe("runtimeSpecifiers", () => {
	it("lists the runtime entries of a set once, sorted", () => {
		expect(runtimeSpecifiers(["trpc-ws", "trpc-sse", "polling"])).toEqual([
			"spinetab/polling/runtime",
			"spinetab/trpc/runtime",
		]);
	});
});
